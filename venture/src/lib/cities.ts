const norm = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();

export function findCity(name: string | null | undefined): City | undefined {
  if (!name) return undefined;
  const n = norm(name);
  return CITIES.find((c) => norm(c.name) === n);
}

export function searchCities(q: string, limit = 8): City[] {
  const n = norm(q);
  if (!n) return [];
  return CITIES.filter((c) => norm(c.name).startsWith(n)).concat(CITIES.filter((c) => !norm(c.name).startsWith(n) && norm(c.name).includes(n))).slice(0, limit);
}
