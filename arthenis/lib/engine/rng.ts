/** Deterministic randomness. The same seed always replays the same history. */
export function hash32(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export type Rng = {
  next(): number;
  chance(p: number): boolean;
  int(min: number, max: number): number;
  pick<T>(arr: readonly T[]): T;
  range(min: number, max: number): number;
  uuid(): string;
};

export function rng(seed: number): Rng {
  let a = seed >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const hex = (n: number) => { let out = ""; while (out.length < n) out += Math.floor(next() * 65536).toString(16).padStart(4, "0"); return out.slice(0, n); };
  return {
    next,
    chance: p => next() < p,
    int: (min, max) => Math.floor(min + next() * (max - min + 1)),
    pick: arr => arr[Math.floor(next() * arr.length) % arr.length],
    range: (min, max) => min + next() * (max - min),
    // RFC 4122 v4 layout, so ids generated by a simulation are valid Postgres uuids.
    uuid: () => `${hex(8)}-${hex(4)}-4${hex(3)}-${(8 + Math.floor(next() * 4)).toString(16)}${hex(3)}-${hex(12)}`
  };
}

/** Name generator seeded by a culture, so a people's names sound like one language. */
export function nameFor(culture: string, r: Rng): string {
  const h = hash32(culture);
  const onsets = ["k", "t", "v", "s", "m", "l", "r", "d", "th", "br", "el", "or", "ka", "z", "n", "ph", "g", "y"];
  const vowels = ["a", "e", "i", "o", "u", "ae", "ia", "ei", "y", "ou"];
  const codas = ["n", "r", "s", "l", "th", "m", "", "", "x", "nd", "rk"];
  const pick = <T,>(arr: T[], k: number) => arr[(h >>> k) % arr.length];
  // Each culture favours a subset of sounds.
  const o = [pick(onsets, 1), pick(onsets, 5), pick(onsets, 9), r.pick(onsets)];
  const v = [pick(vowels, 3), pick(vowels, 7), r.pick(vowels)];
  const c = [pick(codas, 11), pick(codas, 13), r.pick(codas)];
  const syll = () => r.pick(o) + r.pick(v);
  const n = syll() + (r.chance(0.6) ? syll() : "") + r.pick(c);
  return n.charAt(0).toUpperCase() + n.slice(1);
}
